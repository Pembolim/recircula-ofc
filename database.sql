-- ReCircula - esquema PostgreSQL para Supabase
-- Este esquema já foi aplicado no projeto Supabase de produção.
-- Execute somente em um banco novo/vazio.

CREATE TABLE public.usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(100) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    senha varchar(255) NOT NULL,
    criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.objetos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    titulo varchar(120) NOT NULL,
    descricao text NOT NULL,
    tipo varchar(10) NOT NULL CHECK (tipo IN ('doacao', 'troca')),
    imagem varchar(255),
    imagem_bytes bytea,
    imagem_mime varchar(30),
    status varchar(20) NOT NULL DEFAULT 'disponivel'
        CHECK (status IN ('disponivel', 'em_negociacao', 'concluido')),
    criado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT imagem_metadata_consistency CHECK (
        (imagem_bytes IS NULL AND imagem_mime IS NULL) OR
        (imagem_bytes IS NOT NULL AND imagem_mime IN ('image/jpeg', 'image/png', 'image/webp'))
    )
);

CREATE TABLE public.solicitacoes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objeto_id integer NOT NULL REFERENCES public.objetos(id) ON DELETE CASCADE,
    solicitante_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    dono_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    mensagem_inicial varchar(500),
    status varchar(20) NOT NULL DEFAULT 'pendente'
        CHECK (status IN ('pendente', 'aceita', 'recusada', 'concluida')),
    criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.mensagens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id integer NOT NULL REFERENCES public.solicitacoes(id) ON DELETE CASCADE,
    remetente_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    mensagem text NOT NULL,
    enviado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_objetos_status_criado ON public.objetos(status, criado_em DESC);
CREATE INDEX idx_objetos_usuario ON public.objetos(usuario_id);
CREATE INDEX idx_solicitacoes_solicitante ON public.solicitacoes(solicitante_id);
CREATE INDEX idx_solicitacoes_dono ON public.solicitacoes(dono_id);
CREATE INDEX idx_mensagens_solicitacao ON public.mensagens(solicitacao_id, enviado_em);

-- As tabelas são acessadas pelo backend PHP, não diretamente pelo navegador.
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.objetos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.solicitacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mensagens ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.usuarios, public.objetos, public.solicitacoes, public.mensagens
    FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
